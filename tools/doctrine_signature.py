#!/usr/bin/env python3
"""doctrine_signature - generate and verify each discipline's Signature block.

A discipline (a role or a skill) declares its composition across eight mechanism
dimensions: roles, skills, tools, plugins, workflows, hooks, MCP servers,
subagents. This module DERIVES that block from the corpus's own primary sources
so it can never drift out of sync:

  * a role's skills come from its `**Loads.**` / `Load with:` line,
  * subagent backing from the presence of `.claude/agents/<name>.md`,
  * a skill's used-by-roles is the inverse of the parsed role loads,

with two small stable maps (gate ownership; the few skills that carry a real
tool/hook/MCP/workflow) as the only hand-kept config. The block is marker-managed
so hand-written prose around it is never touched (the compiler owns only the block).

Modes:
  --write   regenerate every block into the role + skill files (idempotent)
  --check   (default) re-derive in memory and diff against the committed blocks;
            a mismatch is a finding. Folded into doctrine_lint as check_signatures.
"""

from __future__ import annotations

import argparse
import re
from pathlib import Path

BEGIN = "<!-- SIGNATURE:BEGIN (generated by doctrine_signature - do not edit) -->"
END = "<!-- SIGNATURE:END -->"
NONE = "—"  # em dash = "no capability in this dimension"

